export const ACTION_ICON_NAMES = Object.keys(ACTION_ICONS)

/** The saved icon, or the default of its kind when there is none (or the name is unknown). */
export function ActionIcon({ name, fallback, size = 14 }: { name?: string; fallback: LucideIcon; size?: number }) {
    const Icon = (name && ACTION_ICONS[name]) || fallback
    return <Icon size={size} />
}
